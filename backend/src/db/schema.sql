-- src/db/schema.sql
-- Run this against your Supabase project (SQL editor or CLI).
-- Tables are created in dependency order (no FK forward-references).

-- ─── users ────────────────────────────────────────────────────────────────
-- Mirrors Supabase Auth's auth.users. We keep a public copy for easy JOINs.
create table if not exists users (
  id          uuid primary key default gen_random_uuid(),
  email       text not null unique,
  created_at  timestamptz not null default now()
);

-- ─── projects ─────────────────────────────────────────────────────────────
create table if not exists projects (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references users(id) on delete cascade,
  name        text not null,
  created_at  timestamptz not null default now()
);

create index if not exists projects_user_id_idx on projects(user_id);

-- ─── integrations ─────────────────────────────────────────────────────────
-- One row per (project, provider) pair.
-- access_token is encrypted at rest by Supabase Vault in production.
create table if not exists integrations (
  id            uuid primary key default gen_random_uuid(),
  project_id    uuid not null references projects(id) on delete cascade,
  provider      text not null check (provider in ('github', 'vercel', 'sentry')),
  access_token  text not null,
  status        text not null default 'connected' check (status in ('connected', 'needs_reconnect')),
  created_at    timestamptz not null default now(),
  unique (project_id, provider)
);

create index if not exists integrations_project_id_idx on integrations(project_id);

-- ─── snapshots ────────────────────────────────────────────────────────────
-- Raw data fetched from each provider. Immutable — never update, only insert.
create table if not exists snapshots (
  id          uuid primary key default gen_random_uuid(),
  project_id  uuid not null references projects(id) on delete cascade,
  provider    text not null check (provider in ('github', 'vercel', 'sentry')),
  raw_data    jsonb not null,
  fetched_at  timestamptz not null default now()
);

create index if not exists snapshots_project_provider_idx on snapshots(project_id, provider, fetched_at desc);

-- ─── scores ───────────────────────────────────────────────────────────────
-- One row per (project, category, scored_at). Append-only for trend history.
create table if not exists scores (
  id          uuid primary key default gen_random_uuid(),
  project_id  uuid not null references projects(id) on delete cascade,
  category    text not null check (category in ('security', 'testing', 'dependencies', 'deployment', 'performance', 'overall')),
  value       numeric(5,2) not null check (value >= 0 and value <= 100),
  scored_at   timestamptz not null default now()
);

create index if not exists scores_project_category_idx on scores(project_id, category, scored_at desc);

-- ─── reports ──────────────────────────────────────────────────────────────
-- Weekly report blobs generated by src/reports/weeklyReport.js.
create table if not exists reports (
  id        uuid primary key default gen_random_uuid(),
  user_id   uuid not null references users(id) on delete cascade,
  content   jsonb not null,
  sent_at   timestamptz not null default now()
);

create index if not exists reports_user_id_idx on reports(user_id);

-- ─── ai_insights ──────────────────────────────────────────────────────────
-- Cached plain-English insights generated by Claude Haiku once per day.
create table if not exists ai_insights (
  id          uuid primary key default gen_random_uuid(),
  project_id  uuid not null references projects(id) on delete cascade,
  insight     text not null,
  generated_at timestamptz not null default now()
);

create index if not exists ai_insights_project_idx on ai_insights(project_id, generated_at desc);
